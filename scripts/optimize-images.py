#!/usr/bin/env python3
"""Generates responsive WebP variants (-sm 480w, -md 840w) for every deity
image and writes src/data/imageMeta.ts (aspect ratio + dominant colour) so the
UI can reserve space (no layout shift) and paint an instant colour placeholder.
Usage:  pip install pillow && python3 scripts/optimize-images.py
Originals are never modified."""
import glob, os
from PIL import Image
ROOT = os.path.join(os.path.dirname(__file__), "..")
SIZES = {"sm": 480, "md": 840}
rows = []
for f in sorted(glob.glob(os.path.join(ROOT, "public/assets/images/*Gods/*.webp"))):
    if f.endswith(("-sm.webp", "-md.webp")):
        continue
    im = Image.open(f).convert("RGB")
    w, h = im.size
    for tag, tw in SIZES.items():
        out = f[:-5] + f"-{tag}.webp"
        th = round(h * tw / w)
        im.resize((tw, th), Image.LANCZOS).save(out, "WEBP", quality=76, method=6)
    r, g, b = im.resize((1, 1), Image.BOX).getpixel((0, 0))
    rel = "/" + os.path.relpath(f, os.path.join(ROOT, "public")).replace(os.sep, "/")
    rows.append(f'  "{rel}": {{ w: {w}, h: {h}, color: "#{r:02x}{g:02x}{b:02x}" }},')
with open(os.path.join(ROOT, "src/data/imageMeta.ts"), "w") as fh:
    fh.write("// AUTO-GENERATED by scripts/optimize-images.py. Do not edit by hand.\n")
    fh.write("export const imageMeta: Record<string, { w: number; h: number; color: string }> = {\n")
    fh.write("\n".join(rows) + "\n};\n")
print(len(rows), "images processed")
